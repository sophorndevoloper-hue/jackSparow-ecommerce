#!/bin/sh
set -e

# Make sure all required Laravel storage & runtime directories exist
mkdir -p /var/www/storage/logs \
         /var/www/storage/framework/views \
         /var/www/storage/framework/cache \
         /var/www/storage/framework/sessions \
         /var/www/storage/app/public \
         /var/www/bootstrap/cache \
         /run/nginx

# Pre-create the log file so it gets proper ownership
touch /var/www/storage/logs/laravel.log

# Ensure initial correct permissions
chown -R www-data:www-data /var/www/storage /var/www/bootstrap/cache
chmod -R 775 /var/www/storage /var/www/bootstrap/cache

# 1. Run migrations
php artisan migrate --force || true
# php artisan db:seed --force || true

# 2. Clear any stale caches
php artisan config:clear || true
php artisan cache:clear || true

# 3. Build optimized production caches
php artisan config:cache
php artisan route:cache
php artisan view:cache
php artisan event:cache

# 4. Remove stale symlinks and re-link public storage cleanly
rm -rf /var/www/public/storage
php artisan storage:link --force

# 5. Fix permissions again for files/caches generated by artisan above
chown -R www-data:www-data /var/www/storage /var/www/bootstrap/cache /var/www/public/storage

# 6. Start PHP-FPM in background
php-fpm -D

# 7. Test Nginx config and start web server
nginx -t
exec nginx -g "daemon off;"